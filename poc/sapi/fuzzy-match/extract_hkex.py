"""Build data/hkex_cases.py from HKEX announcements crawled by SADI (data/hkex_articles.tsv: stock code, body).

An announcement's header names the issuer in English and Chinese just before "(Incorporated …" or
"(A joint stock company …)", e.g. "Grand Pharmaceutical Group Limited 遠大醫藥集團有限公司* (Incorporated in
Bermuda …) (Stock Code: 00512)". Each language's legal name becomes a case labeled with the announcement's code.

Export first (local SADI DB):
    psql … -At -F $'\\t' -c "select r.extra_metadata->'stock_code'->>1, regexp_replace(coalesce(c.body_cleaned,
      r.body),'\\s+',' ','g') from raw_news r left join cleaned_news c using(raw_id) where source_name='HKEX'"
"""

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
HEADER = re.compile(
    r"(?:contents of this \w+\.|this \w+\.)\s*(?P<names>[^()]{4,160}?)\s*\((?:Incorporated|A joint stock|"
    r"H Shares|a company incorporated|incorporated)", re.I)
CJK = re.compile(r"[一-鿿]")
LISTED = json.loads((HERE / "stock_list_snapshot.json").read_text())

# Usage: extract_hkex.py [input.tsv output.py] — the held-out run skips companies already in data/hkex_cases.py.
SRC = HERE / (sys.argv[1] if len(sys.argv) > 1 else "data/hkex_articles.tsv")
DST = HERE / (sys.argv[2] if len(sys.argv) > 2 else "data/hkex_cases.py")
EXCLUDED: set[str] = set()
if DST.name != "hkex_cases.py":
    sys.path.insert(0, str(HERE / "data"))
    from hkex_cases import HKEX_CASES as _USED  # noqa: E402
    EXCLUDED = {c[1] for c in _USED}

seen: dict[str, str] = {}
for line in SRC.read_text().splitlines():
    raw_code, body = line.split("\t", 1)
    code = raw_code.removeprefix("Code:")
    if not re.fullmatch(r"\d{5}", code) or code not in LISTED or code in EXCLUDED:
        continue  # several codes in one row (e.g. "0231882318"): ambiguous label
    m = HEADER.search(body[:3000])
    if not m:
        continue
    names = m.group("names").replace("*", "").strip()
    first_cjk = CJK.search(names)
    en = (names[:first_cjk.start()] if first_cjk else names).strip(" ,")
    zh = names[first_cjk.start():].strip() if first_cjk else ""
    trailing_en = re.search(r"\s([A-Z][A-Z0-9 .,&'’-]{5,})$", zh)
    if trailing_en:  # "中原銀行股份有限公司 ZHONGYUAN BANK CO., LTD."
        zh, en = zh[:trailing_en.start()].strip(), en or trailing_en.group(1).strip()
    for name, lang in ((en, "hkex_legal_en"), (zh, "hkex_legal_zh")):
        if 4 <= len(name) <= 60 and len(re.findall(r"[A-Za-z\u4e00-\u9fff]", name)) >= 3 and re.fullmatch(r"[\w\s.,&'’()\-\u4e00-\u9fff]+", name) and not name.lower().startswith(("this ", "the stock exchange", "hong kong exchanges")):
            seen.setdefault(name, (code, lang))

out = ['"""Generated by extract_hkex.py from HKEX announcements crawled 2026-10-24."""', "",
       "HKEX_CASES = ["]
out += [f"    ({name!r}, {code!r}, {lang!r}, 'HKEX announcement header'),"
        for name, (code, lang) in sorted(seen.items(), key=lambda kv: kv[1])]
out.append("]")
DST.write_text("\n".join(out) + "\n")
print(len(seen), "cases")
